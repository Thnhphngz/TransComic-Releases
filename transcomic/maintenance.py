"""Conservative cache inventory and recoverable cleanup. Never a release action."""
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
from uuid import uuid4
from .release_adapters import safe_path
from .update.metadata import UpdateError


def active_work():
    """Return only IDs/categories, never process command lines or credentials."""
    if os.name!='nt':raise UpdateError('PROCESS_INSPECTION_NOT_READY')
    script="Get-CimInstance Win32_Process | Where-Object { ($_.Name -match '^(pythonw?|TransComic|ISCC)\\.exe$') -and ($_.Name -match '^(TransComic|ISCC)\\.exe$' -or $_.CommandLine -match 'pytest|PyInstaller|live_|release_transcomic|update_helper|run_transcomic') } | Select-Object ProcessId | ConvertTo-Json -Compress"
    result=subprocess.run(['powershell','-NoProfile','-NonInteractive','-Command',script],capture_output=True,text=True,timeout=20,shell=False)
    if result.returncode:raise UpdateError('PROCESS_INSPECTION_NOT_READY')
    data=json.loads(result.stdout) if result.stdout.strip() else []
    if isinstance(data,dict):data=[data]
    return [item['ProcessId'] for item in data if item['ProcessId']!=os.getpid()]


def git_files(root):
    def call(args):
        run=subprocess.run(['git','-C',str(root),*args],capture_output=True,timeout=20,shell=False)
        if run.returncode:raise UpdateError('CLEANUP_GIT_UNVERIFIED')
        return run.stdout
    tracked=set(call(['ls-files','-z']).decode('utf8').split('\0'))-{''}
    ignored=set(call(['ls-files','--others','--ignored','--exclude-standard','-z']).decode('utf8').split('\0'))-{''}
    return tracked,ignored


def tree(root):
    # Inspect reparse nodes themselves but never descend into them.
    stack=[root]
    while stack:
        path=stack.pop();stat=path.lstat()
        reparse=path.is_symlink() or bool(getattr(stat,'st_file_attributes',0)&0x400)
        yield path,stat,reparse
        if path.is_dir() and not reparse:
            stack.extend(sorted(path.iterdir(),reverse=True))


def digest(path):return hashlib.sha256(path.read_bytes()).hexdigest()


def inventory(root,tracked=None,ignored=None):
    root=safe_path(root)
    if tracked is None:tracked,ignored=git_files(root)
    ignored=ignored or set();records=[];candidates=[]
    references=[]
    for folder in ('docs','scripts','tests','transcomic'):
        base=root/folder
        if base.is_dir():
            for path,stat,reparse in tree(base):
                if not reparse and path.is_file() and path.suffix in ('.py','.md','.toml','.bat','.iss'):
                    references.append((path.relative_to(root).as_posix(),path.read_text(encoding='utf8',errors='replace')))
    for path,stat,reparse in tree(root):
        rel=path.relative_to(root).as_posix()
        if rel=='.' or rel=='.git' or rel.startswith('.git/'):continue
        if path.is_file() or reparse:
            group='A' if rel in tracked or rel.startswith(('transcomic/','scripts/','tests/','docs/','installer/')) else 'C' if rel.startswith(('artifacts/','build/','dist/')) else 'D'
            if not reparse and path.suffix=='.pyc' and '__pycache__' in path.parts:group='B'
            records.append({'path':rel,'kind':'reparse' if reparse else 'file','bytes':stat.st_size,
                            'git':'tracked' if rel in tracked else 'ignored' if rel in ignored else 'untracked',
                            'reparse':reparse,'group':group,'in_use':'process gate required','recreatable':group=='B',
                            'referenced_by':[name for name,text in references if rel in text],
                            'risk':'keep by default' if group!='B' else 'generated bytecode'})
        if path.is_dir() and not reparse and (path.name=='__pycache__' or (path.parent==root and path.name.startswith('.pytest_'))):
            # No source/artifact/build directory is eligible; preserve evidence and all data files.
            if rel.startswith(('artifacts/','build/','dist/','.git/')):continue
            nodes=list(tree(path));files=[p for p,s,r in nodes if not p.is_dir() or r]
            contains_tracked=any(name==rel or name.startswith(rel+'/') for name in tracked)
            refs=[name for name,text in references if rel in text]
            pure_bytecode=path.name=='__pycache__' and all(p.suffix=='.pyc' for p in files)
            pytest_cache=path.name=='.pytest_cache' and (path/'CACHEDIR.TAG').is_file() and all(
                p.relative_to(path).as_posix() in ('.gitignore','CACHEDIR.TAG','README.md','v/cache/nodeids','v/cache/lastfailed','v/cache/stepwise') for p in files)
            if pure_bytecode or pytest_cache:
                # A mention of the generic cache name in maintenance/tests is not a dependency.
                # Exact cached-file references still force retention.
                refs=[name for name,text in references if any(p.relative_to(root).as_posix() in text for p in files)]
            safe=not contains_tracked and not any(r for p,s,r in nodes) and not refs and (pure_bytecode or pytest_cache or not files)
            candidates.append({'path':rel,'bytes':sum(s.st_size for p,s,r in nodes if not p.is_dir()),
                               'safe':safe,'reason':'recreatable cache' if safe else 'tracked/reference/reparse/data/evidence; keep',
                               'referenced_by':refs,'files':{p.relative_to(root).as_posix():digest(p) for p in files if p.is_file() and not p.is_symlink() and not getattr(p.lstat(),'st_file_attributes',0)&0x400}})
    # Nested candidates are handled through their outer candidate only.
    candidates=[c for c in candidates if not any(c['path'].startswith(other['path']+'/') and other['safe'] for other in candidates)]
    return {'root':str(root),'files':records,'candidates':candidates,'root_items':len(list(root.iterdir())),
            'file_count':len(records),'directory_count':sum(1 for p,s,r in tree(root) if p.is_dir() and '.git' not in p.relative_to(root).parts)}


def require_idle(root,processes):
    if processes:raise UpdateError('CLEANUP_ACTIVE_PROCESS')
    journal=root/'.release-state'/'journal.json'
    if journal.exists():
        safe_path(journal,root)
        try:state=json.loads(journal.read_text(encoding='utf8'))['state']
        except Exception:raise UpdateError('CLEANUP_RELEASE_STATE_UNCERTAIN') from None
        if state!='PUBLISHED':raise UpdateError('CLEANUP_PENDING_RELEASE')


def cleanup(root,plan,backup_root,*,processes=None,tracked=None):
    root=safe_path(root);backup_root=safe_path(backup_root)
    if backup_root.is_relative_to(root):raise UpdateError('CACHE_BACKUP_MUST_BE_OUTSIDE_WORKSPACE')
    if Path(plan['root'])!=root:raise UpdateError('CLEANUP_ROOT_MISMATCH')
    require_idle(root,active_work() if processes is None else processes)
    if tracked is None:tracked,_=git_files(root)
    # Recompute eligibility to reject changed data/references/tracked state, not only hashes.
    fresh=inventory(root,tracked,set())
    fresh_safe={c['path']:c for c in fresh['candidates'] if c['safe']}
    chosen=[c for c in plan['candidates'] if c['safe']]
    for item in chosen:
        path=safe_path(root/item['path'],root)
        if path==root or item['path'] not in fresh_safe or item['files']!=fresh_safe[item['path']]['files']:
            raise UpdateError('CACHE_CHANGED_OR_UNSAFE')
    quarantine=backup_root/('cleanup-'+uuid4().hex)
    quarantine.mkdir(parents=True,exist_ok=False)
    deleted=[]
    receipt=quarantine/'cleanup-receipt.json'
    def progress(state,item=None):
        with receipt.open('w',encoding='utf8') as stream:
            json.dump({'state':state,'current':item,'deleted':deleted,'candidates':chosen},stream,indent=2)
            stream.flush();os.fsync(stream.fileno())
    progress('PLANNED')
    for item in chosen:
        path=safe_path(root/item['path'],root)
        require_idle(root,active_work() if processes is None else processes)
        # Backup and verify all bytes before deleting one candidate; preserve recovery evidence.
        for rel,expected in item['files'].items():
            src=safe_path(root/rel,root);dst=safe_path(quarantine/rel,quarantine)
            if rel in tracked or digest(src)!=expected:raise UpdateError('CACHE_CHANGED_OR_TRACKED')
            dst.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(src,dst)
            if digest(dst)!=expected:raise UpdateError('CACHE_BACKUP_FAILED')
        progress('BACKUP_VERIFIED',item['path'])
        nodes=list(tree(path))
        for node,stat,reparse in reversed(nodes):
            safe_path(node,root)
            if reparse:raise UpdateError('CACHE_REPARSE_CHANGED')
            if node.is_dir():node.rmdir()
            else:
                rel=node.relative_to(root).as_posix()
                if rel in tracked or rel not in item['files'] or digest(node)!=item['files'][rel]:raise UpdateError('CACHE_CHANGED_OR_TRACKED')
                node.unlink()
        deleted.append(item['path'])
        progress('CANDIDATE_REMOVED',item['path'])
    result={'deleted':deleted,'quarantine':str(quarantine),'bytes':sum(c['bytes'] for c in chosen),
            'restore_policy':'copy verified cache bytes back only after reviewing destination; never overwrite data'}
    with receipt.open('w',encoding='utf8') as stream:
        json.dump({'state':'COMPLETE','result':result,'candidates':chosen},stream,indent=2)
        stream.flush();os.fsync(stream.fileno())
    return result
